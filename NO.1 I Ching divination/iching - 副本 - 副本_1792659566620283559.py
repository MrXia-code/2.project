class IChingApp:
    def __init__(self, root):
        self.root = root
        self.root.title("周易六十四卦【自用学习版】")
        self.root.geometry("700x600")

        # 顶部按钮区
        frame_top = ttk.Frame(root)
        frame_top.pack(pady=10)
        ttk.Button(frame_top, text="铜钱起卦", command=self.cast).grid(row=0, column=0, padx=10)
        ttk.Button(frame_top, text="清空", command=self.clear).grid(row=0, column=1, padx=10)

        # 卦象画布
        self.canvas = tk.Canvas(root, width=200, height=240, bg="#f8f8f8")
        self.canvas.pack()

        # 结果文本框
        self.txt = scrolledtext.ScrolledText(root, width=80, height=12)
        self.txt.pack(pady=10)

    def cast(self):
        """模拟三枚铜钱摇卦，得到六爻（自下而上）"""
        lines = []
        self.txt.delete(1.0, tk.END)
        self.txt.insert(tk.END, "=== 摇卦记录（自下而上初爻至上爻）===\n")
        for i in range(6):
            coins = [random.randint(2,3) for _ in range(3)]
            s = sum(coins)
            if s == 6:
                yao = 0; typ = "老阴（变）"
            elif s ==7:
                yao =1; typ="少阳"
            elif s ==8:
                yao=0; typ="少阴"
            else:
                yao=1; typ="老阳（变）"
            lines.append(yao)
            self.txt.insert(tk.END,f"第{i+1}爻：{typ} | 铜钱：{coins}\n")
        # lines[0]初爻，lines[5]上爻；卦码是上爻在前
        hex_code = "".join(str(x) for x in reversed(lines))
        # 匹配卦
        gua_name, gua_ci, gua_bin, gua_char = None, None, None, None
        for name, ci, b, char in hexagram_data:
            if b == hex_code:
                gua_name, gua_ci, gua_char = name, ci, char
                break
        # 绘制卦象
        self.draw_hexagram(lines)
        self.txt.insert(tk.END, f"\n【所得卦】{gua_char} {gua_name}\n卦辞：{gua_ci}\n")
        self.txt.insert(tk.END, "\n⚠️ 本程序仅用于传统文化学习，不作吉凶判断。")

    def draw_hexagram(self, yao_list):
        """画六爻，yao_list[0]=初爻，最下面"""
        self.canvas.delete("all")
        y_start = 220
        for yao in yao_list:
            if yao ==1:
                # 阳爻 一整横
                self.canvas.create_line(30, y_start, 170, y_start, width=4)
            else:
                # 阴爻 断开
                self.canvas.create_line(30, y_start, 80, y_start, width=4)
                self.canvas.create_line(120, y_start,170,y_start, width=4)
            y_start -=35

    def clear(self):
        self.canvas.delete("all")
        self.txt.delete(1.0, tk.END)

if __name__ == "__main__":
    root = tk.Tk()
    app = IChingApp(root)
    root.mainloop()